async function sendActivationFailure(req, failureInfo) {
  var info = collectRequestInfo(req);
  var subject = "[Activation Failed] " + (failureInfo.productId || "?") +
    " - " + (failureInfo.redeemCode || "?") +
    " | " + (info.os || "?") + " " + (info.device || "?") +
    " - " + (failureInfo.reason || "Unknown error");

  var htmlBody = buildHtmlEmail(info, {
    redeemCode: failureInfo.redeemCode || "-",
    productId: failureInfo.productId || "-",
    deviceId: failureInfo.deviceId || "-",
    months: failureInfo.months || "-",
    activationCode: "-",
    source: failureInfo.source || "user",
  });
  htmlBody += "<tr><td style='padding:4px 12px 4px 0;color:#ef4444;white-space:nowrap;vertical-align:top'>Error</td>" +
    "<td style='padding:4px 0;color:#ef4444'>" + escapeHtml(failureInfo.reason || "Unknown error") + "</td></tr>";

  var textBody = buildTextEmail(info, {
    redeemCode: failureInfo.redeemCode || "-",
    productId: failureInfo.productId || "-",
    deviceId: failureInfo.deviceId || "-",
    months: failureInfo.months || "-",
    activationCode: "-",
    source: failureInfo.source || "user",
  });
  textBody += "\nError: " + (failureInfo.reason || "Unknown error");

  var fromAddr = NOTIFY_FROM_NAME + " <" + SMTP_USER + ">";

  if (SMTP_PASS) {
    try {
      await sendViaSMTP(fromAddr, NOTIFY_TO, subject, htmlBody, textBody);
      await logEmailEvent({
        type: "activation",
        to: NOTIFY_TO,
        subject: subject,
        status: "success",
        source: "failure-notify",
        visitor: info,
      });
    } catch (e) {
      console.error("[notify] Failed to send failure email:", e.message);
      await logEmailEvent({
        type: "activation",
        to: NOTIFY_TO,
        subject: subject,
        status: "failed",
        error: e.message,
        source: "failure-notify",
        visitor: info,
      });
    }
  } else {
    console.log("[notify] Activation failure:", failureInfo.reason);
    await logEmailEvent({
      type: "activation",
      to: NOTIFY_TO,
      subject: subject,
      status: "skipped",
      error: failureInfo.reason || "Unknown error",
      source: "failure-notify",
      visitor: info,
    });
  }
}

